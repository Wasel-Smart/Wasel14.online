function lookup(
  key: string,
  lang: Language,
): string | undefined {
  const keys = key.split('.');
  let node: Record<string, unknown> | string | undefined = translations[lang];
  for (const k of keys) {
    if (typeof node === 'object' && node !== null && k in node) {
      node = node[k] as Record<string, unknown> | string;
    } else {
      return undefined;
    }
  }
  return typeof node === 'string' ? node : undefined;
}

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (typeof template !== 'string' || !params) {return template;}
  return template.replace(/\{(\w+)\}/g, (_match, name: string) =>
    params[name] !== undefined ? String(params[name]) : `{${name}}`,
  );
}

export function t(key: TranslationKey, langOrParams?: Language | Record<string, string | number>, maybeParams?: Record<string, string | number>): string {
  let lang: Language = 'ar';
  let params: Record<string, string | number> | undefined;

  if (typeof langOrParams === 'string') {
    lang = langOrParams;
    params = maybeParams;
  } else if (typeof langOrParams === 'object' && langOrParams !== null) {
    lang = 'ar';
    params = langOrParams;
  }

  const direct = lookup(key, lang);
  if (direct !== undefined) {return interpolate(direct, params);}

  const fallbackLang: Language = lang === 'en' ? 'ar' : 'en';
  const fallback = lookup(key, fallbackLang);
  return interpolate(fallback !== undefined ? fallback : key, params);
}

export function getTranslations(lang: Language): Record<string, unknown> {
  return translations[lang] as Record<string, unknown>;
}

export function useTranslation(language: Language) {
  return {
    t: (key: TranslationKey, replacements?: Record<string, string | number>) => t(key, language, replacements),
    getTranslations: (lang: Language) => getTranslations(lang),
    translations,
  };
}
